// Pure helpers over a project's canvas, shared by the main process and the renderer.

import { PROJECT_WORKSPACE_DIR } from './constants'
import {
  EMPTY_CANVAS,
  type CanvasAgentNode,
  type CanvasNoteNode,
  type CanvasPortalNode,
  type Project,
  type ProjectCanvas,
} from './types'

/** Size of an agent placed without one (canvas units). */
export const AGENT_NODE_SIZE = { width: 560, height: 360 }
/** Space left between nodes placed automatically. */
const PLACEMENT_GAP = 80

/** The project's canvas with every list present, whichever version saved it. */
export function canvasOf(project: Pick<Project, 'canvas'>): Required<ProjectCanvas> {
  const canvas = project.canvas ?? EMPTY_CANVAS
  return {
    nodes: canvas.nodes,
    notes: canvas.notes ?? [],
    texts: canvas.texts ?? [],
    portals: canvas.portals ?? [],
    edges: canvas.edges,
  }
}

/** Ids of every node on the canvas, of any kind. */
export function nodeIds(canvas: ProjectCanvas): Set<string> {
  return new Set([
    ...canvas.nodes.map((node) => node.agentId),
    ...(canvas.notes ?? []).map((note) => note.id),
    ...(canvas.texts ?? []).map((text) => text.id),
    ...(canvas.portals ?? []).map((portal) => portal.id),
  ])
}

/**
 * Ids of notes and portals are generated by Veltrix; anything else could point outside the
 * notes folder or into another file.
 */
export function isNoteId(id: string): boolean {
  return /^[A-Za-z0-9_-]{1,64}$/.test(id)
}

/** Where a note's markdown lives, relative to the project folder (as given to agents). */
export function notePath(noteId: string): string {
  if (!isNoteId(noteId)) throw new Error(`Invalid note id "${noteId}".`)
  return `${PROJECT_WORKSPACE_DIR}/notes/${noteId}.md`
}

/** A note's name: the one the user gave it, or its first line without markdown marks. */
export function noteTitle(note: Pick<CanvasNoteNode, 'title'>, content: string): string {
  if (note.title?.trim()) return note.title.trim()
  const firstLine = content.split('\n').find((line) => line.trim()) ?? ''
  return firstLine
    .replace(/^\s*(#+|[-*+]\s+\[[ xX]\]|[-*+]|\d+\.)\s*/, '')
    .replace(/[*_`~]/g, '')
    .trim()
}

/** Ticked and total items of the markdown checklists in `content`. */
export function checklistProgress(content: string): { done: number; total: number } {
  const items = content.match(/^\s*[-*+]\s+\[[ xX]\]/gm) ?? []
  const done = items.filter((item) => /\[[xX]\]$/.test(item)).length
  return { done, total: items.length }
}

/**
 * Notes an agent may read and edit: those linked to it, plus every note chained to them
 * through note-to-note lines.
 */
export function notesOfAgent(canvas: ProjectCanvas, agentId: string): CanvasNoteNode[] {
  const notes = new Map((canvas.notes ?? []).map((note) => [note.id, note]))
  const neighbours = (id: string): string[] =>
    canvas.edges.flatMap((edge) =>
      edge.from === id ? [edge.to] : edge.to === id ? [edge.from] : [],
    )

  const reached = new Set<string>()
  const queue = neighbours(agentId).filter((id) => notes.has(id))
  while (queue.length) {
    const id = queue.shift()!
    if (reached.has(id)) continue
    reached.add(id)
    queue.push(...neighbours(id).filter((next) => notes.has(next) && !reached.has(next)))
  }
  return [...reached].map((id) => notes.get(id)!)
}

/** Portals an agent is linked to directly (portals don't chain like notes). */
export function portalsOfAgent(canvas: ProjectCanvas, agentId: string): CanvasPortalNode[] {
  const linked = new Set(
    canvas.edges.flatMap((e) => (e.from === agentId ? [e.to] : e.to === agentId ? [e.from] : [])),
  )
  return (canvas.portals ?? []).filter((portal) => linked.has(portal.id))
}

/** Only web pages and the blank page may load in a portal. */
export function isPortalUrl(url: string): boolean {
  return url === 'about:blank' || /^https?:\/\/[^\s]+$/i.test(url)
}

/**
 * Puts a recruit on the canvas in a row below its manager, after the recruits already there,
 * and links the two both ways so they can message each other.
 */
export function withRecruit(
  canvas: ProjectCanvas,
  managerId: string,
  recruitId: string,
  siblingIds: string[],
): ProjectCanvas {
  const manager = canvas.nodes.find((node) => node.agentId === managerId)
  const placed = canvas.nodes.filter((node) => siblingIds.includes(node.agentId)).length
  const x = (manager?.x ?? 0) + placed * (AGENT_NODE_SIZE.width + PLACEMENT_GAP)
  const y = manager ? manager.y + manager.height + PLACEMENT_GAP * 1.5 : 0
  const id = (from: string, to: string): string => `${from}->${to}`
  return {
    ...canvas,
    nodes: [...canvas.nodes, { agentId: recruitId, x, y, ...AGENT_NODE_SIZE }],
    edges: [
      ...canvas.edges,
      { id: id(managerId, recruitId), from: managerId, to: recruitId },
      { id: id(recruitId, managerId), from: recruitId, to: managerId },
    ],
  }
}

/**
 * Places agents that aren't on the canvas yet in a row below everything already there,
 * so a team the orchestrator assembles shows up together.
 */
export function withAgentNodes(canvas: ProjectCanvas, agentIds: string[]): ProjectCanvas {
  const placed = new Set(canvas.nodes.map((node) => node.agentId))
  const fresh = agentIds.filter((id) => !placed.has(id))
  if (fresh.length === 0) return canvas

  const boxes = [
    ...canvas.nodes,
    ...(canvas.notes ?? []),
    ...(canvas.texts ?? []),
    ...(canvas.portals ?? []),
  ]
  const top = boxes.length ? Math.max(...boxes.map((box) => box.y + box.height)) + PLACEMENT_GAP : 0
  const left = boxes.length ? Math.min(...boxes.map((box) => box.x)) : 0
  const nodes: CanvasAgentNode[] = fresh.map((agentId, index) => ({
    agentId,
    x: left + index * (AGENT_NODE_SIZE.width + PLACEMENT_GAP),
    y: top,
    ...AGENT_NODE_SIZE,
  }))
  return { ...canvas, nodes: [...canvas.nodes, ...nodes] }
}
